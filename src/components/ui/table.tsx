import * as React from "react";
import { cn } from "@/lib/utils";

/**
 * Table — docs/05-DESIGN-SYSTEM.md §6 component inventory: "Table". Plain
 * HTML table wrappers, no Radix (a table has no interaction model Radix
 * needs to manage).
 *
 * docs/05 §11 calls for alternating row tints on spec tables. This is left
 * to callers rather than baked into `TableRow`, since not every table wants
 * zebra striping (e.g. a 2-row spec summary vs. a 40-row admin data table).
 * Apply it per-table with `odd:bg-surface-container-lowest
 * even:bg-surface-container` on `TableRow`'s `className` where needed.
 */
export const Table = React.forwardRef<HTMLTableElement, React.HTMLAttributes<HTMLTableElement>>(
  ({ className, ...props }, ref) => (
    <div className="relative w-full overflow-auto">
      <table ref={ref} className={cn("w-full caption-bottom text-body-sm", className)} {...props} />
    </div>
  ),
);
Table.displayName = "Table";

